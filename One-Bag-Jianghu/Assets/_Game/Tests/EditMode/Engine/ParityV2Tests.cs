using System.Collections.Generic;
using System.IO;
using Newtonsoft.Json.Linq;
using NUnit.Framework;
using OneBagJianghu.Engine;
using UnityEngine;

namespace OneBagJianghu.Tests.Engine
{
    public sealed class ParityV2Tests
    {
        public static IEnumerable<string> Cases()
        {
            string folder = Path.Combine(Application.dataPath, "_Game/Tests/EditMode/Data/ParityV2");
            foreach (string file in Directory.GetFiles(folder, "case_*.json"))
            {
                yield return file;
            }
        }

        [TestCaseSource(nameof(Cases))]
        public void ItemsV2GoldenCaseMatchesEveryEvent(string file)
        {
            // Goldens were generated by Java from this Items v2 catalog (tools/parity/make_golden.py --items).
            ItemCatalog items =
ItemCatalog.Load(File.ReadAllText(Path.Combine(Application.dataPath,
"_Game/Tests/EditMode/Data/ParityV2/items-v2.json")));
            SectCatalog sects =
SectCatalog.Load(File.ReadAllText(Path.Combine(Application.dataPath,
"_Game/Resources/Data/sects.json")));
            JObject golden = JObject.Parse(File.ReadAllText(file));
            JObject expected = (JObject)golden["expected"];
            expected.Remove("draw");
            JObject actual =
new BattleSimulator(items,
sects,
BattleConfig.Defaults()).Run(golden["a"].ToObject<Loadout>(),
golden["b"].ToObject<Loadout>(),
golden.Value<long>("seed")).ToJObject();
            foreach (string field in new[]
            {
                "winner",
                "durationMs",
                "finalHp",
                "bags",
                "items"
            }

            )
            {
                Assert.That(JToken.DeepEquals(expected[field],
actual[field]),
Is.True,
Path.GetFileName(file) +
" field " +
field);
            }

            JArray ee = (JArray)expected["events"], ae = (JArray)actual["events"];
            Assert.That(ae.Count,
Is.EqualTo(ee.Count),
Path.GetFileName(file) + " event count");
            for (int i = 0; i < ee.Count; i++)
            {
                if (!JToken.DeepEquals(ee[i], ae[i]))
                {
                    Assert.Fail(Path.GetFileName(file) + " event " +
i +
"\nexpected: " +
ee[i] +
"\nactual: " +
ae[i]);
                }
            }
        }
    }
}